"""Expose the *existing* CFOS-compatible Mac LinuxKit toolchain without rebuilding it.

The only generated output is a sourceable shell environment in sibling Builds.
Missing external host executables are diagnosed, never secretly installed into
$HOME or the source repository. Xcode Command Line Tools are a prerequisite.
"""
from __future__ import annotations

import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess

from managed_backend import host_executable

REQUIRED = ('linuxkit', 'docker', 'colima', 'cmake', 'xcrun', 'codesign')


def expose(builds: Path) -> Path:
    if platform.system() != 'Darwin' or platform.machine() != 'arm64':
        raise RuntimeError('The copied CFOS LinuxKit/Rosetta launcher requires Apple Silicon macOS')
    builds = Path(builds).resolve()
    if builds.name != 'Builds':
        raise RuntimeError('Toolchain environment must be generated in sibling Builds')
    tools = {name: host_executable(name) for name in REQUIRED}
    missing = sorted(name for name, exe in tools.items() if not exe)
    if missing:
        raise RuntimeError('Existing CFOS LinuxKit toolchain incomplete: ' + ', '.join(missing)
                           + '; provision the original CFOS Mac host prerequisites, not the Ubuntu image')
    result = subprocess.run([tools['xcrun'], '--find', 'swiftc'], text=True,
                            capture_output=True, check=False, timeout=20)
    if result.returncode or not result.stdout.strip():
        raise RuntimeError('Xcode Command Line Tools do not expose swiftc')
    locations = list(dict.fromkeys(str(Path(tools[name]).resolve().parent) for name in REQUIRED))
    output = builds / 'CinterForgeTerminal/Toolchains/mac/env.sh'
    output.parent.mkdir(parents=True, exist_ok=True)
    # This is a read-only PATH facade over the same installed tools, not a
    # second toolchain or a modification of the user's shell startup scripts.
    value = ':'.join(locations)
    script = ('# Generated by CinterForgeTerminal setup; source from Mac Terminal or CinterForgeTerminal.\n'
              '# Tool binaries are the *existing* macOS tools; only this facade lives in Builds.\n'
              f'export PATH={shlex.quote(value)}:"$PATH"\n')
    if not output.is_file() or output.read_text(encoding='utf-8') != script:
        output.write_text(script, encoding='utf-8')
    return output


if __name__ == '__main__':
    import sys
    repo = Path(__file__).resolve().parents[1]
    try:
        print(expose(repo.parent / 'Builds'))
    except (OSError, RuntimeError) as exc:
        print(f'[CinterForgeTerminal Mac toolchain] {exc}', file=sys.stderr)
        raise SystemExit(1)
